-- BeeWeek: ejecutar en el SQL Editor de Supabase con una copia de seguridad previa.
-- Conserva las cuentas existentes y actualiza sus hashes SHA-256 a bcrypt al entrar.
create schema if not exists private;
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.usuarios (
    id bigint generated by default as identity primary key,
    identificacion varchar(20) unique not null,
    nombre varchar(100) not null,
    apellido varchar(100) not null,
    email varchar(150) unique not null,
    username varchar(50) unique not null,
    password_hash varchar(255) not null,
    rol varchar(50) not null default 'Estudiante',
    activo boolean not null default true,
    created_at timestamptz not null default now()
);

create or replace function private.beeweek_login(p_login text, p_password text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare cuenta public.usuarios%rowtype;
        clave text := pg_catalog.btrim(p_password);
        coincide boolean := false;
begin
    if pg_catalog.btrim(coalesce(p_login, '')) = '' or clave = '' then
        return null;
    end if;
    select * into cuenta from public.usuarios
    where pg_catalog.lower(username) = pg_catalog.lower(pg_catalog.btrim(p_login))
       or pg_catalog.lower(email) = pg_catalog.lower(pg_catalog.btrim(p_login))
    limit 1;
    if not found or not cuenta.activo then return null; end if;
    if cuenta.password_hash like '$2%' then
        coincide := extensions.crypt(clave, cuenta.password_hash) = cuenta.password_hash;
    elsif cuenta.password_hash ~ '^[0-9a-f]{64}$' then
        coincide := cuenta.password_hash = pg_catalog.encode(
            extensions.digest(pg_catalog.convert_to(clave, 'UTF8'), 'sha256'), 'hex');
        if coincide then
            update public.usuarios
            set password_hash = extensions.crypt(clave, extensions.gen_salt('bf', 12))
            where id = cuenta.id;
        end if;
    end if;
    if not coincide then return null; end if;
    return pg_catalog.jsonb_build_object(
        'id', cuenta.id, 'identificacion', cuenta.identificacion,
        'nombre', cuenta.nombre, 'apellido', cuenta.apellido,
        'email', cuenta.email, 'username', cuenta.username,
        'rol', cuenta.rol, 'activo', cuenta.activo);
end;
$$;

create or replace function private.beeweek_register(
    p_identificacion text, p_nombre text, p_apellido text,
    p_email text, p_username text, p_password text, p_rol text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare cuenta public.usuarios%rowtype;
begin
    if p_identificacion !~ '^[0-9]{10}$'
       or pg_catalog.btrim(coalesce(p_nombre, '')) = ''
       or pg_catalog.btrim(coalesce(p_apellido, '')) = ''
       or pg_catalog.length(pg_catalog.btrim(coalesce(p_username, ''))) < 4
       or pg_catalog.length(pg_catalog.btrim(coalesce(p_password, ''))) < 8
       or pg_catalog.lower(pg_catalog.btrim(coalesce(p_email, ''))) !~ '^[^@ ]+@uleam[.]edu[.]ec$'
       or p_rol not in ('Docente', 'Estudiante') then
        raise exception 'Datos de registro inválidos' using errcode = '22023';
    end if;
    insert into public.usuarios
        (identificacion, nombre, apellido, email, username, password_hash, rol)
    values (pg_catalog.btrim(p_identificacion), pg_catalog.btrim(p_nombre),
        pg_catalog.btrim(p_apellido), pg_catalog.lower(pg_catalog.btrim(p_email)),
        pg_catalog.btrim(p_username),
        extensions.crypt(pg_catalog.btrim(p_password), extensions.gen_salt('bf', 12)),
        p_rol)
    returning * into cuenta;
    return pg_catalog.jsonb_build_object('id', cuenta.id);
exception when unique_violation then
    raise exception 'Ya existe una cuenta con esa identificación, usuario o correo.'
        using errcode = '23505';
end;
$$;

-- Las funciones públicas son invoker; la lógica privilegiada queda en private.
create or replace function public.beeweek_login(p_login text, p_password text)
returns jsonb language sql security invoker set search_path = ''
as $$ select private.beeweek_login(p_login, p_password); $$;
create or replace function public.beeweek_register(
    p_identificacion text, p_nombre text, p_apellido text,
    p_email text, p_username text, p_password text, p_rol text)
returns jsonb language sql security invoker set search_path = ''
as $$ select private.beeweek_register(
    p_identificacion, p_nombre, p_apellido, p_email, p_username, p_password, p_rol); $$;

revoke all on function private.beeweek_login(text, text) from public, anon, authenticated;
revoke all on function private.beeweek_register(text, text, text, text, text, text, text)
    from public, anon, authenticated;
revoke all on function public.beeweek_login(text, text) from public, anon, authenticated;
revoke all on function public.beeweek_register(text, text, text, text, text, text, text)
    from public, anon, authenticated;
grant usage on schema private to anon, authenticated;
grant execute on function private.beeweek_login(text, text) to anon, authenticated;
grant execute on function private.beeweek_register(text, text, text, text, text, text, text)
    to anon, authenticated;
grant execute on function public.beeweek_login(text, text) to anon, authenticated;
grant execute on function public.beeweek_register(text, text, text, text, text, text, text)
    to anon, authenticated;

drop policy if exists "Permitir lectura de usuarios para login" on public.usuarios;
drop policy if exists "Permitir registro de nuevos usuarios" on public.usuarios;
drop policy if exists "Permitir actualizacion de usuarios" on public.usuarios;
alter table public.usuarios enable row level security;
revoke all on public.usuarios from public, anon, authenticated;

