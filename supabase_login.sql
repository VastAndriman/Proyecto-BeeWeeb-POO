-- 1. Crear la tabla de usuarios
CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR(20) UNIQUE NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(50) DEFAULT 'Docente' NOT NULL, -- 'Administrador', 'Docente', 'Estudiante'
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;

-- 3. Crear políticas para acceso con clave anon/service_role
DROP POLICY IF EXISTS "Permitir lectura de usuarios para login" ON public.usuarios;
CREATE POLICY "Permitir lectura de usuarios para login" 
ON public.usuarios FOR SELECT 
USING (true);

DROP POLICY IF EXISTS "Permitir registro de nuevos usuarios" ON public.usuarios;
CREATE POLICY "Permitir registro de nuevos usuarios" 
ON public.usuarios FOR INSERT 
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir actualizacion de usuarios" ON public.usuarios;
CREATE POLICY "Permitir actualizacion de usuarios" 
ON public.usuarios FOR UPDATE 
USING (true);

